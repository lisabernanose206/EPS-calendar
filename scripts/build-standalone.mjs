import { generateNotFound } from "./build-errors.mjs";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
const read = relative => readFile(new URL(relative, new URL("../", import.meta.url)), "utf8");
const [template, styles, errorStyles, shell, bundle] = await Promise.all([
  read("src/standalone.template.html"),
  read("src/styles.css"),
  read("src/ui/error-state.css"),
  read("src/app/shell.html"),
  build({
    absWorkingDir: root,
    entryPoints: ["src/standalone.js"],
    bundle: true,
    write: false,
    format: "iife",
    target: "es2020",
    charset: "utf8",
    plugins: [{
      name: "html-text",
      setup(builder) {
        builder.onLoad({ filter: /\.html$/ }, async args => ({
          contents: await readFile(args.path.replace(/\?raw$/, ""), "utf8"),
          loader: "text"
        }));
      }
    }]
  })
]);

const script = bundle.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const output = template
  .replace("APP_SCRIPT_HASH", createHash("sha256").update("\n" + script).digest("base64"))
  .replace("<!-- APP_STYLES -->", () => `<style>\n${styles}
${errorStyles}</style>`)
  .replace("<!-- APP_SHELL -->", () => shell)
  .replace("<!-- APP_SCRIPT -->", () => `<script>\n${script}</script>`);
await writeFile(new URL("../standalone.html", import.meta.url),
  "<!-- Generated by npm run build:standalone. Edit src/ instead. -->\n" + output, "utf8");
console.log("standalone.html generated from src/ (UTF-8).");

await generateNotFound();
